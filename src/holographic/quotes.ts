/**
 * یک جمله تصادفی برمی‌گرداند و تا حد امکان از تکرارِ جملهٔ قبلی پرهیز می‌کند.
 */
export function getRandomQuote(excludeId?: string): Quote | null {
  if (QUOTES.length === 0) {
    return null;
  }
  if (QUOTES.length === 1) {
    return QUOTES[0];
  }
  let pick = QUOTES[Math.floor(Math.random() * QUOTES.length)];
  let guard = 0;
  while (pick.id === excludeId && guard < 10) {
    pick = QUOTES[Math.floor(Math.random() * QUOTES.length)];
    guard += 1;
  }
  return pick;
}
